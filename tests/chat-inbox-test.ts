import assert from 'node:assert/strict'
import type { ChatMessage } from '../shared/protocol'
import { emptyChatInbox, readChatInbox, receiveChatHistory, receiveChatMessage } from '../src/multiplayer/chatInbox'

const message = (id: string, senderId = 'other'): ChatMessage => ({ id, senderId, senderName: senderId, text: id, timestamp: 1, reactions: { '❤️': [], '😂': [], '💀': [] } })
const old = message('old')
let inbox = receiveChatHistory(emptyChatInbox('room:self'), [old], 'self')
assert.deepEqual(inbox.unreadIds, [], 'initial history is a silent baseline')
assert.equal(inbox.notification, null)
inbox = receiveChatMessage(inbox, message('live'), 'self')
assert.deepEqual(inbox.unreadIds, ['live'])
assert.equal(inbox.notification?.id, 'live')
assert.equal(receiveChatMessage(inbox, message('live'), 'self'), inbox, 'duplicate live ID has no effect')
inbox = receiveChatMessage(inbox, message('mine', 'self'), 'self')
assert.deepEqual(inbox.unreadIds, ['live'])
assert.equal(inbox.notification, null, 'own messages do not alert')
inbox = receiveChatHistory(inbox, [old, message('live'), message('mine', 'self'), message('missed')], 'self')
assert.deepEqual(inbox.unreadIds, ['live', 'missed'], 'catch-up adds unread without recounting known messages')
assert.equal(inbox.notification, null, 'history never alerts')
inbox = receiveChatHistory(inbox, inbox.messages, 'self')
assert.deepEqual(inbox.unreadIds, ['live', 'missed'])
const saved = JSON.parse(JSON.stringify({ knownIds: inbox.knownIds, unreadIds: inbox.unreadIds, olderUnread: inbox.olderUnread }))
let restored = receiveChatHistory(emptyChatInbox('room:self', saved), [...inbox.messages, message('during-refresh')], 'self')
assert.deepEqual(restored.unreadIds, ['live', 'missed', 'during-refresh'])
assert.equal(restored.notification, null)
restored = readChatInbox(restored)
assert.deepEqual(restored.unreadIds, [])
assert.equal(readChatInbox(restored), restored, 'read observation is idempotent')
restored = receiveChatHistory(restored, [...restored.messages, message('after-read')], 'self')
assert.deepEqual(restored.unreadIds, ['after-read'], 'previously read messages stay read on reconnect')
const truncated = receiveChatHistory(restored, Array.from({ length: 50 }, (_, i) => message(`new-${i}`)), 'self')
assert.equal(truncated.messages.length, 50)
assert.equal(truncated.olderUnread, true, 'a missing history overlap must not claim an exact unread count')
assert.equal(truncated.notification, null)
assert.equal(readChatInbox(truncated).olderUnread, false)
let liveOverflow = readChatInbox(inbox)
for (let i = 0; i < 60; i++) liveOverflow = receiveChatMessage(liveOverflow, message(`burst-${i}`), 'self')
assert.equal(liveOverflow.messages.length, 50)
assert.equal(liveOverflow.unreadIds.length, 50)
assert.equal(liveOverflow.olderUnread, true)
assert.deepEqual(receiveChatHistory(emptyChatInbox('other-room'), [old], 'self').unreadIds, [], 'new rooms have an independent baseline')
for (const bad of [null, {}, { knownIds: ['old'], unreadIds: ['missing'], olderUnread: false }, { knownIds: [1], unreadIds: [], olderUnread: false }]) assert.equal(emptyChatInbox('room', bad).baseline, false)
assert.equal(receiveChatHistory(emptyChatInbox(), [old, old], 'self').messages.length, 1)
console.log('Chat inbox: history, live deduplication, own messages, read state, refresh, reconnect, bounded history and storage validation passed')
const liveForRead = receiveChatMessage(receiveChatHistory(emptyChatInbox(), [], 'self'), message('visible-live'), 'self')
assert.equal(readChatInbox(liveForRead).notification?.id, 'visible-live', 'measuring read state must not consume a live event before its notification effect')
